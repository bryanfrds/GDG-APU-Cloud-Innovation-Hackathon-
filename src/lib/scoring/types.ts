/**
 * types.ts — Shared data contracts for the Prove It application.
 *
 * This file defines the shape of every major data object passed between the
 * four tasks (Submissions, Voice Viva, Scoring & Insights, Lecturer Dashboard).
 *
 * NO logic lives here — only TypeScript interface definitions.
 * All four teammates should agree on this file before writing their own code.
 *
 * Firestore collections these types map to:
 *   submissions/{submissionId}         → Submission       (written by Task 1)
 *   vivaTranscripts/{vivaId}           → VivaTranscript   (written by Task 2)
 *   vivaReports/{vivaId}               → VivaReport       (written by Task 3)
 *   classStats/{assignmentId}          → ClassStats       (written by Task 3)
 */

// ---------------------------------------------------------------------------
// TASK 1 → TASK 3
// Submission — the student's uploaded assignment and the questions generated
// for it by Gemini. Task 1 writes this; Task 3 reads it during scoring.
// ---------------------------------------------------------------------------

/** A single question generated by Gemini about the student's submission. */
export interface Question {
  /** Unique ID for this question, generated by Task 1. */
  questionId: string;

  /** The question text shown to the student, e.g. "Why did you use a loop on line 40?" */
  questionText: string;

  /**
   * The exact lines of code the question refers to.
   * Task 3 uses this when checking whether the student's answer matches the code.
   * Task 1 must provide this — without it, inconsistency detection cannot work.
   */
  relevantCodeSnippet: string;

  /**
   * The concept area this question tests, e.g. "loops", "recursion", "error handling".
   * Task 3 uses this to group questions for the class-wide topic breakdown.
   * Task 1 must provide this — without it, the class view topic stats cannot be built.
   */
  topic: string;
}

/** The student's assignment submission, including extracted text and generated questions. */
export interface Submission {
  /** Unique ID for this submission, generated by Task 1. */
  submissionId: string;

  /** The student who submitted the assignment. */
  studentId: string;

  /** Which assignment this submission belongs to. */
  assignmentId: string;

  /** When the student submitted. Stored as a Firestore Timestamp or ISO string. */
  submittedAt: string;

  /** Cloud Storage URL pointing to the uploaded file (PDF, code file, zip, etc.). */
  fileUrl: string;

  /**
   * The full text extracted from the submitted file.
   * Task 1 provides this if it can extract text (e.g. from a .py or .txt file).
   * Null if the file type does not support text extraction (e.g. a compiled binary).
   * Task 3 uses this for inconsistency detection alongside the student's answers.
   */
  submittedText: string | null;

  /** The list of questions Gemini generated about this specific submission. */
  questions: Question[];
}

// ---------------------------------------------------------------------------
// TASK 2 → TASK 3
// VivaTranscript — everything recorded during one viva session.
// Task 2 writes this; Task 3 reads it to score the student's answers.
// Each viva attempt is a separate document, keyed by vivaId.
// ---------------------------------------------------------------------------

/** One student answer recorded during the viva. */
export interface VivaAnswer {
  /**
   * Must match a questionId from the Submission.
   * Task 3 uses this to look up the relevantCodeSnippet and topic for that question.
   */
  questionId: string;

  /**
   * The question text, repeated here so Task 3 does not need a separate read
   * just to display or evaluate the question.
   */
  questionText: string;

  /**
   * The full transcript of what the student said or typed in response.
   * This is the primary input Gemini will score.
   */
  studentAnswer: string;

  /**
   * How many follow-up questions the AI asked before moving on.
   * INFORMATIONAL ONLY — does not affect any score calculation.
   * Displayed on the lecturer report as context.
   */
  followUpCount: number;

  /**
   * How long the student took to answer, in milliseconds.
   * INFORMATIONAL ONLY — does not affect any score calculation.
   * Displayed on the lecturer report as context.
   */
  answerDurationMs: number;
}

/** A complete record of one viva session for one student on one submission. */
export interface VivaTranscript {
  /**
   * Unique ID for this viva session, generated by Task 2 at the start of the viva.
   * This is the Firestore document ID for vivaReports as well, ensuring multiple
   * attempts are stored separately and nothing is ever overwritten.
   */
  vivaId: string;

  /** Links back to the submission this viva is about. */
  submissionId: string;

  /** The student who did this viva. */
  studentId: string;

  /** Which assignment this viva is for. */
  assignmentId: string;

  /**
   * Which attempt this is: 1 for the first viva, 2 for a second attempt, etc.
   * Task 2 sets this by counting existing transcripts for the same
   * studentId + assignmentId before writing.
   * Task 4 uses this to display "Attempt 1", "Attempt 2" in the lecturer view.
   */
  attemptNumber: number;

  /** When the viva session started. */
  startedAt: string;

  /** When the viva session ended. */
  completedAt: string;

  /**
   * Whether the student used voice or the text-chat fallback.
   * Displayed on the report for lecturer context.
   */
  mode: "voice" | "text";

  /** The student's answers, one entry per question. */
  answers: VivaAnswer[];
}

// ---------------------------------------------------------------------------
// TASK 3 OUTPUT → TASK 4
// VivaReport — the scored result of one viva session.
// Task 3 writes this; Task 4 reads it to display the per-student report.
// Document ID in Firestore: vivaId (same as the transcript, never overwritten).
// ---------------------------------------------------------------------------

/** One question's scored result, as evaluated by Gemini. */
export interface ScoredAnswer {
  /** Matches the questionId from the original Submission and VivaTranscript. */
  questionId: string;

  /** The question text, carried through for display. */
  questionText: string;

  /** What the student actually said or typed. */
  studentAnswer: string;

  /** The concept area, carried through from the Question for topic breakdown. */
  topic: string;

  /**
   * The score Gemini assigned to this answer: 0 (no understanding) to 10 (full understanding).
   * Based on understanding of the student's own code, not on fluency or grammar.
   */
  score: number;

  /** A one-sentence explanation from Gemini of why this score was given. */
  feedback: string;

  /**
   * How many follow-ups were asked. Carried through from VivaAnswer.
   * INFORMATIONAL ONLY — not used in any calculation.
   */
  followUpCount: number;

  /**
   * How long the student took to answer, in milliseconds. Carried through from VivaAnswer.
   * INFORMATIONAL ONLY — not used in any calculation.
   */
  answerDurationMs: number;
}

/**
 * The inconsistency check result — always kept separate from the understanding score.
 * A flag here is a prompt for the lecturer to have a conversation with the student.
 * It is never treated as proof of misconduct and never changes the score.
 */
export interface InconsistencyResult {
  /** True if Gemini detected a notable mismatch between the answers and the submitted code. */
  flagged: boolean;

  /**
   * Specific evidence for the flag: a direct quote or reference from the student's answer
   * and/or the submitted code that shows the mismatch.
   * Null if flagged is false.
   * This must be specific — vague summaries are not acceptable as evidence.
   */
  evidence: string | null;

  /**
   * How significant the mismatch appears.
   * "minor"   — small inconsistency, may be a slip or nerves.
   * "notable" — clear mismatch that warrants a conversation.
   * Null if flagged is false.
   * Deliberately avoids language like "suspicious" or "likely AI-generated".
   */
  severity: "minor" | "notable" | null;
}

/** A brief summary of the strongest or weakest answer, for the top of the report. */
export interface AnswerSummary {
  questionId: string;
  questionText: string;
  score: number;
  feedback: string;
}

/** The complete scored report for one viva attempt. Task 4 reads this for the lecturer view. */
export interface VivaReport {
  /**
   * Same as the vivaId of the transcript this report is based on.
   * Also the Firestore document ID — one report per viva, never overwritten.
   */
  vivaId: string;

  submissionId: string;
  studentId: string;
  assignmentId: string;

  /** Copied from the VivaTranscript so Task 4 can display attempt history. */
  attemptNumber: number;

  /** When Task 3 finished scoring this viva. */
  scoredAt: string;

  /**
   * The overall understanding score: 0–100.
   * Calculated as: average of all question scores (each 0–10), multiplied by 10.
   * This is derived purely from Gemini's per-answer scores and simple arithmetic.
   */
  overallScore: number;

  /**
   * A human-readable label derived from overallScore using provisional thresholds.
   * Thresholds are defined in scoringConfig.ts, not hardcoded here.
   * Current provisional values: Strong ≥ 75, Adequate ≥ 50, Needs Review < 50.
   */
  scoreLabel: "Strong" | "Adequate" | "Needs Review";

  /** All answers with their individual Gemini scores and feedback. */
  scoredAnswers: ScoredAnswer[];

  /** The single answer with the highest score. */
  strongestAnswer: AnswerSummary;

  /** The single answer with the lowest score. */
  weakestAnswer: AnswerSummary;

  /**
   * The inconsistency check result.
   * Completely separate from overallScore and scoreLabel.
   * Task 4 should display this in a visually distinct section of the report.
   */
  inconsistency: InconsistencyResult;
}

// ---------------------------------------------------------------------------
// TASK 3 OUTPUT → TASK 4
// ClassStats — aggregated statistics across all students for one assignment.
// Task 3 writes this; Task 4 reads it for the class-wide dashboard view.
// Document ID in Firestore: assignmentId (recalculated aggregate, safe to overwrite).
// ---------------------------------------------------------------------------

/** Per-topic performance breakdown for the class view. */
export interface TopicBreakdown {
  /** The topic name, e.g. "recursion", "loops", "error handling". */
  topic: string;

  /** Average score (0–100) across all questions in this topic across all students. */
  averageScore: number;

  /**
   * Total number of individual question scores that contributed to this average.
   * (Multiple students × multiple questions on the same topic.)
   */
  questionCount: number;

  /**
   * True if averageScore is below the "Needs Review" threshold in scoringConfig.ts.
   * Signals to the lecturer that this topic should be retaught.
   */
  flagged: boolean;
}

/** A brief record of a student who may need the lecturer's attention. */
export interface FlaggedStudent {
  studentId: string;

  /** The student's overall understanding score (0–100). */
  overallScore: number;

  /** Whether the inconsistency check was flagged for this student. */
  inconsistencyFlagged: boolean;
}

/** Class-wide statistics for one assignment, built from all VivaReports. */
export interface ClassStats {
  /** Which assignment these stats are for. */
  assignmentId: string;

  /** When these stats were last calculated. */
  calculatedAt: string;

  /**
   * Number of students who have at least one completed viva for this assignment.
   * If a student has multiple attempts, they are counted once (latest attempt used).
   */
  totalStudents: number;

  /** Average overallScore across all included students: 0–100. */
  averageScore: number;

  /** Count of students in each score band. */
  scoreDistribution: {
    /** Students scoring at or above the Strong threshold. */
    strong: number;
    /** Students scoring at or above the Adequate threshold, below Strong. */
    adequate: number;
    /** Students scoring below the Adequate threshold. */
    needsReview: number;
  };

  /**
   * Per-topic performance, sorted by averageScore ascending (weakest topics first).
   * Flagged topics appear first in the lecturer view.
   */
  topicBreakdown: TopicBreakdown[];

  /**
   * Students who scored below the Needs Review threshold or had an inconsistency flag.
   * The lecturer sees this list and decides whether to follow up.
   */
  flaggedStudents: FlaggedStudent[];
}
